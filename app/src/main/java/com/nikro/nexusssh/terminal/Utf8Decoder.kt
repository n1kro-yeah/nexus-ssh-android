package com.nikro.nexusssh.terminal

/**
 * Incremental UTF-8 decoder.
 *
 * SSH delivers bytes in arbitrary chunks, so a multi-byte character routinely straddles two
 * reads. Feed bytes one at a time; the decoder returns -1 until a full code point is available.
 * Malformed sequences yield U+FFFD instead of throwing, which is what a terminal must do.
 */
class Utf8Decoder {

    private var codePoint = 0
    private var remaining = 0
    private var minimum = 0

    fun reset() {
        codePoint = 0
        remaining = 0
        minimum = 0
    }

    /**
     * @param byte the next byte, 0..255
     * @return a code point, or -1 when more bytes are needed
     */
    fun decode(byte: Int): Int {
        val value = byte and 0xFF

        if (remaining > 0) {
            if (value and 0xC0 != 0x80) {
                // Not a continuation byte: drop the partial sequence and restart with this byte.
                reset()
                return if (value < 0x80) value else decode(value)
            }
            codePoint = (codePoint shl 6) or (value and 0x3F)
            remaining--
            if (remaining > 0) return -1
            val result = codePoint
            val floor = minimum
            reset()
            return when {
                result < floor -> REPLACEMENT // overlong encoding
                result in 0xD800..0xDFFF -> REPLACEMENT // surrogate half
                result > 0x10FFFF -> REPLACEMENT
                else -> result
            }
        }

        return when {
            value < 0x80 -> value

            value in 0xC2..0xDF -> {
                codePoint = value and 0x1F
                remaining = 1
                minimum = 0x80
                -1
            }

            value in 0xE0..0xEF -> {
                codePoint = value and 0x0F
                remaining = 2
                minimum = 0x800
                -1
            }

            value in 0xF0..0xF4 -> {
                codePoint = value and 0x07
                remaining = 3
                minimum = 0x10000
                -1
            }

            // 0x80..0xC1 and 0xF5..0xFF can never start a valid sequence.
            else -> REPLACEMENT
        }
    }

    companion object {
        const val REPLACEMENT = 0xFFFD
    }
}

/**
 * Column width of a code point, following Markus Kuhn's `wcwidth` tables plus the emoji ranges
 * added by Unicode 9. The terminal must agree with the remote's idea of width or the cursor
 * drifts and redraws corrupt the screen.
 */
object CharWidth {

    fun of(codePoint: Int): Int = when {
        codePoint == 0 -> 0
        codePoint < 32 -> 0
        codePoint == 0x7F -> 0
        isCombining(codePoint) -> 0
        isWide(codePoint) -> 2
        else -> 1
    }

    /** Total width of a string, used to lay out prompts and truncate labels. */
    fun widthOf(text: String): Int {
        var width = 0
        var index = 0
        while (index < text.length) {
            val codePoint = text.codePointAt(index)
            width += of(codePoint)
            index += Character.charCount(codePoint)
        }
        return width
    }

    fun isCombining(codePoint: Int): Boolean {
        if (codePoint < 0x0300) return false
        var i = 0
        while (i < COMBINING.size) {
            if (codePoint < COMBINING[i]) return false
            if (codePoint <= COMBINING[i + 1]) return true
            i += 2
        }
        return false
    }

    fun isWide(codePoint: Int): Boolean {
        if (codePoint < 0x1100) return false
        var i = 0
        while (i < WIDE.size) {
            if (codePoint < WIDE[i]) return false
            if (codePoint <= WIDE[i + 1]) return true
            i += 2
        }
        return false
    }

